class Transformador(ElementoRed):
    """Representa un transformador eléctrico."""

    def __init__(
        self,
        Id: str,
        potencia_maxima_mw: float,
        voltaje_entrada_nominal: float,
        voltaje_salida_nominal: float,
        polaridad: str,
    ) -> None:
        """Inicializa un transformador.

        Args:
            Id: Identificador único del transformador.
            potencia_maxima_mw: Potencia máxima en MW.
            voltaje_entrada_nominal: Voltaje nominal de entrada.
            voltaje_salida_nominal: Voltaje nominal de salida.
            polaridad: Polaridad del transformador.
        """
        super().__init__(Id, potencia_maxima_mw)
        self.voltaje_entrada_nominal: float = voltaje_entrada_nominal
        self.voltaje_salida_nominal: float = voltaje_salida_nominal
        self.polaridad: str = polaridad
        self.voltaje_entrada_actual: float = 0.0
        self.voltaje_salida_actual: float = 0.0
        self.__potencia_actual_mw: float = 0.0

    def obtener_potencia_actual_mw(self) -> float:
        """Devuelve la potencia actual del transformador en MW."""
        return self.__potencia_actual_mw

    def cambiar_voltaje_entrada(self, nuevo_voltaje: float) -> None:
        """Modifica el voltaje de entrada si no supera el nominal.

        Args:
            nuevo_voltaje: Nuevo voltaje de entrada.
        """
        if nuevo_voltaje <= self.voltaje_entrada_nominal:
            self.voltaje_entrada_actual = nuevo_voltaje
        elif nuevo_voltaje > self.voltaje_entrada_nominal:
            print(
                "Voltaje supera al voltaje nominal. "
                "Ingrese un voltaje menor"
            )
        else:
            print("Entrada inválida")


