import numpy as np


class ElementoRed:
    """Representa un elemento genérico de una red eléctrica. Actualmente
    es clase padre de Carga,Generador,Transformador,LineaTransmisión y
    LineaDistribución"""

    def __init__(self, Id: str, potencia_maxima_mw: float) -> None:
        """Inicializa un elemento de la red.

        Args:
            Id: Identificador único del elemento.
            potencia_maxima_mw: Potencia máxima admisible en MW.
        """
        self.Id: str = Id
        self.__potencia_maxima_mw: float = potencia_maxima_mw
        self.__conectado: bool = False
        self.__mantencion: bool = False
        self.__potencia_actual_mw: float = 0.0

    def estado_de_conexion(self) -> bool:
        """Devuelve el estado de conexión del elemento."""
        return self.__conectado

    def estado_de_mantenimiento(self) -> bool:
        """Devuelve si el elemento está en mantenimiento."""
        return self.__mantencion

    def conectar(self) -> None:
        """Conecta el elemento a la red."""
        self.__conectado = True

    def desconectar(self) -> None:
        """Desconecta el elemento de la red."""
        self.__conectado = False

    def entrar_en_modo_mantencion(self) -> None:
        """Desconecta el elemento y lo pone en mantenimiento."""
        self.__conectado = False
        self.__mantencion = True

    def salir_del_modo_mantencion(self) -> None:
        """Saca al elemento del modo de mantenimiento."""
        self.__mantencion = False

    def cambiar_potencia_maxima(
        self, potencia_maxima_nueva_mw: float
    ) -> None:
        """Modifica la potencia máxima admisible del elemento.

        Args:
            potencia_maxima_nueva_mw: Nueva potencia máxima en MW.
        """
        self.__potencia_maxima_mw = potencia_maxima_nueva_mw

    def obtener_potencia_maxima(self) -> float:
        """Devuelve la potencia máxima del elemento en MW."""
        return self.__potencia_maxima_mw

    def obtener_potencia_actual_mw(self) -> float:
        """Devuelve la potencia actual del elemento en MW."""
        return self.__potencia_actual_mw


